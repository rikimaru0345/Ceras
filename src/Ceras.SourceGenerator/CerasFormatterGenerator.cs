using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace Ceras.SourceGenerator;

/// <summary>
/// Roslyn incremental source generator that emits IFormatter&lt;T&gt; implementations for
/// every type decorated with [GenerateFormatter].  The generated code mirrors what the
/// old AotGeneratorApp produced, but runs automatically at compile time.
/// </summary>
[Generator]
public sealed class CerasFormatterGenerator : IIncrementalGenerator
{
    const string GenerateFormatterFqn = "Ceras.GenerateFormatterAttribute";
    // Also support the legacy AotGenerator namespace for backwards compatibility
    // (ForAttributeWithMetadataName only accepts one name; users should prefer the new Ceras namespace)
    const string IncludeFqn           = "Ceras.IncludeAttribute";
    const string ExcludeFqn           = "Ceras.ExcludeAttribute";
    const string MemberConfigFqn      = "Ceras.MemberConfigAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Collect every type symbol that carries [GenerateFormatter]
        IncrementalValuesProvider<INamedTypeSymbol> types = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                GenerateFormatterFqn,
                predicate: static (node, _) => node is TypeDeclarationSyntax,
                transform: static (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol)
            .WithComparer(SymbolEqualityComparer.Default);

        // Also grab the compilation so we can resolve attribute symbols
        IncrementalValueProvider<(Compilation, ImmutableArray<INamedTypeSymbol>)> combined =
            context.CompilationProvider.Combine(types.Collect());

        context.RegisterSourceOutput(combined, static (spc, pair) =>
        {
            var (compilation, targetTypes) = pair;
            if (targetTypes.IsEmpty)
                return;

            Execute(spc, compilation, targetTypes);
        });
    }

    static void Execute(
        SourceProductionContext context,
        Compilation compilation,
        ImmutableArray<INamedTypeSymbol> types)
    {
        // Resolve attribute symbols once
        var includeAttr      = compilation.GetTypeByMetadataName(IncludeFqn);
        var excludeAttr      = compilation.GetTypeByMetadataName(ExcludeFqn);
        var memberConfigAttr = compilation.GetTypeByMetadataName(MemberConfigFqn);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// ReSharper disable All");
        sb.AppendLine("#nullable disable");
        sb.AppendLine("#pragma warning disable 649");
        sb.AppendLine();
        sb.AppendLine("using Ceras;");
        sb.AppendLine("using Ceras.Formatters;");
        sb.AppendLine();
        sb.AppendLine("namespace Ceras.Generated");
        sb.AppendLine("{");

        // --- Registration helper ------------------------------------------------
        sb.AppendLine("    public static class GeneratedFormatters");
        sb.AppendLine("    {");
        sb.AppendLine("        /// <summary>");
        sb.AppendLine("        /// Call this before creating your CerasSerializer to use the pre-generated");
        sb.AppendLine("        /// formatters instead of runtime code generation.");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine("        public static void UseFormatters(SerializerConfig config)");
        sb.AppendLine("        {");
        foreach (var type in types)
        {
            string typeName      = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            string formatterName = MakeFormatterClassName(type);
            sb.AppendLine($"            config.ConfigType<{typeName}>().CustomFormatter = new {formatterName}();");
        }
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        // --- One formatter class per type ----------------------------------------
        foreach (var type in types)
        {
            var members = DiscoverMembers(type, includeAttr, excludeAttr, memberConfigAttr);

            if (members.Count == 0)
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    Diag.NoSerializableMembers,
                    type.Locations.FirstOrDefault(),
                    type.Name));
            }

            WriteFormatterClass(sb, type, members);
        }

        sb.AppendLine("}"); // close namespace
        sb.AppendLine("#nullable restore");
        sb.AppendLine("#pragma warning restore 649");

        context.AddSource("CerasGeneratedFormatters.g.cs",
            SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    // -------------------------------------------------------------------------
    // Member discovery
    // -------------------------------------------------------------------------

    static List<SerializedMember> DiscoverMembers(
        INamedTypeSymbol type,
        INamedTypeSymbol? includeAttr,
        INamedTypeSymbol? excludeAttr,
        INamedTypeSymbol? memberConfigAttr)
    {
        // Check for [MemberConfig] on the type to determine which member kinds are targeted
        TargetMemberKind targetKind = GetTargetMemberKind(type, memberConfigAttr);

        var members = new List<SerializedMember>();

        foreach (var member in type.GetMembers())
        {
            if (member.IsStatic || member.IsImplicitlyDeclared)
                continue;

            bool hasInclude = includeAttr != null && HasAttribute(member, includeAttr);
            bool hasExclude = excludeAttr != null && HasAttribute(member, excludeAttr);

            if (hasExclude)
                continue;

            if (member is IFieldSymbol field)
            {
                if (field.IsConst || field.IsReadOnly)
                    continue;

                bool included = hasInclude || IsFieldIncluded(field, targetKind);
                if (!included)
                    continue;

                members.Add(new SerializedMember(field.Name, field.Type, isField: true));
            }
            else if (member is IPropertySymbol prop)
            {
                if (prop.IsReadOnly || prop.IsWriteOnly || prop.IsIndexer)
                    continue;
                if (prop.GetMethod == null || prop.SetMethod == null)
                    continue;

                bool included = hasInclude || IsPropertyIncluded(prop, targetKind);
                if (!included)
                    continue;

                members.Add(new SerializedMember(prop.Name, prop.Type, isField: false));
            }
        }

        // Sort members using the same comparer as Ceras's SchemaMemberComparer so that
        // the generated formatter produces byte-identical output to DynamicFormatter.
        // Key: TypeFullName + MemberName + DeclaringTypeFullName + "f"/"p"
        // Build sort keys using SortKeyFormat (no UseSpecialTypes) so that CLR type
        // names match what SchemaMemberComparer.GetComparisonName uses at runtime
        // (m.MemberType.FullName gives "System.Single", not "float", etc.).
        string DeclaringFqn = type.ToDisplayString(SortKeyFormat);
        members.Sort((a, b) =>
        {
            string ka = a.Type.ToDisplayString(SortKeyFormat)
                      + a.Name
                      + DeclaringFqn
                      + (a.IsField ? "f" : "p");
            string kb = b.Type.ToDisplayString(SortKeyFormat)
                      + b.Name
                      + DeclaringFqn
                      + (b.IsField ? "f" : "p");
            return string.Compare(ka, kb, StringComparison.Ordinal);
        });

        return members;
    }

    static TargetMemberKind GetTargetMemberKind(INamedTypeSymbol type, INamedTypeSymbol? memberConfigAttr)
    {
        if (memberConfigAttr == null)
            return TargetMemberKind.PublicFields; // Ceras default

        foreach (var attr in type.GetAttributes())
        {
            if (!SymbolEqualityComparer.Default.Equals(attr.AttributeClass, memberConfigAttr))
                continue;

            // TargetMembers is the first constructor argument (it's an enum)
            if (attr.ConstructorArguments.Length > 0 &&
                attr.ConstructorArguments[0].Value is int raw)
            {
                return (TargetMemberKind)raw;
            }

            // Check named args
            foreach (var named in attr.NamedArguments)
            {
                if (named.Key == "TargetMembers" && named.Value.Value is int rawNamed)
                    return (TargetMemberKind)rawNamed;
            }
        }

        return TargetMemberKind.PublicFields; // Ceras default
    }

    static bool IsFieldIncluded(IFieldSymbol field, TargetMemberKind kind)
    {
        bool isPublic = field.DeclaredAccessibility == Accessibility.Public;

        if ((kind & TargetMemberKind.PublicFields) != 0 && isPublic)
            return true;
        if ((kind & TargetMemberKind.PrivateFields) != 0 && !isPublic)
            return true;

        return false;
    }

    static bool IsPropertyIncluded(IPropertySymbol prop, TargetMemberKind kind)
    {
        bool isPublic = prop.DeclaredAccessibility == Accessibility.Public;

        if ((kind & TargetMemberKind.PublicProperties) != 0 && isPublic)
            return true;
        if ((kind & TargetMemberKind.PrivateProperties) != 0 && !isPublic)
            return true;

        return false;
    }

    static bool HasAttribute(ISymbol symbol, INamedTypeSymbol attributeType)
    {
        foreach (var attr in symbol.GetAttributes())
            if (SymbolEqualityComparer.Default.Equals(attr.AttributeClass, attributeType))
                return true;
        return false;
    }

    // -------------------------------------------------------------------------
    // Code generation
    // -------------------------------------------------------------------------

    static void WriteFormatterClass(StringBuilder sb, INamedTypeSymbol type, List<SerializedMember> members)
    {
        string typeName      = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string formatterName = MakeFormatterClassName(type);

        sb.AppendLine($"    internal sealed class {formatterName} : IFormatter<{typeName}>");
        sb.AppendLine("    {");

        // --- Formatter fields (one per distinct member type) ---------------------
        var seenFieldNames = new HashSet<string>();
        foreach (var m in members)
        {
            string fieldName = MakeFormatterFieldName(m.Type);
            if (!seenFieldNames.Add(fieldName))
                continue; // same formatter field already declared

            string memberTypeName = m.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            sb.AppendLine($"        IFormatter<{memberTypeName}> {fieldName};");
        }
        sb.AppendLine();

        // --- Serialize ----------------------------------------------------------
        sb.AppendLine($"        public void Serialize(ref byte[] buffer, ref int offset, {typeName} value)");
        sb.AppendLine("        {");
        foreach (var m in members)
        {
            string fieldName = MakeFormatterFieldName(m.Type);
            sb.AppendLine($"            {fieldName}.Serialize(ref buffer, ref offset, value.{m.Name});");
        }
        sb.AppendLine("        }");
        sb.AppendLine();

        // --- Deserialize --------------------------------------------------------
        sb.AppendLine($"        public void Deserialize(byte[] buffer, ref int offset, ref {typeName} value)");
        sb.AppendLine("        {");
        foreach (var m in members)
        {
            string fieldName     = MakeFormatterFieldName(m.Type);
            string memberTypeName = m.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            if (m.IsField)
            {
                // Can pass fields directly by ref
                sb.AppendLine($"            {fieldName}.Deserialize(buffer, ref offset, ref value.{m.Name});");
            }
            else
            {
                // Properties need a temporary local
                string tmp = "_tmp" + m.Name;
                sb.AppendLine($"            {memberTypeName} {tmp} = value.{m.Name};");
                sb.AppendLine($"            {fieldName}.Deserialize(buffer, ref offset, ref {tmp});");
                sb.AppendLine($"            value.{m.Name} = {tmp};");
            }
        }
        sb.AppendLine("        }");

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // -------------------------------------------------------------------------
    // Naming helpers
    // -------------------------------------------------------------------------

    static string MakeFormatterClassName(INamedTypeSymbol type)
        => SanitizeIdentifier(type.ToDisplayString(FullyQualifiedNoGlobal)) + "Formatter";

    static string MakeFormatterFieldName(ITypeSymbol type)
    {
        string raw   = SanitizeIdentifier(type.ToDisplayString(FullyQualifiedNoGlobal));
        string lower = char.ToLowerInvariant(raw[0]) + raw.Substring(1);
        return "_" + lower + "Formatter";
    }

    /// Strips namespace qualifiers and sanitizes to a valid C# identifier.
    static string SanitizeIdentifier(string displayName)
    {
        var sb = new StringBuilder(displayName.Length);
        foreach (char c in displayName)
        {
            if (char.IsLetterOrDigit(c))
                sb.Append(c);
            else if (c == '_')
                sb.Append('_');
            // skip dots, angle brackets, commas, spaces
        }
        return sb.Length == 0 ? "Unknown" : sb.ToString();
    }

    // Display format that produces fully-qualified names WITHOUT the "global::" prefix,
    // used for class-name and formatter-field-name generation (UseSpecialTypes gives
    // readable names like "float" rather than "System.Single" in generated code).
    static readonly SymbolDisplayFormat FullyQualifiedNoGlobal = new SymbolDisplayFormat(
        globalNamespaceStyle:     SymbolDisplayGlobalNamespaceStyle.Omitted,
        typeQualificationStyle:   SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions:          SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions:     SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    // Display format for computing sort keys — must match the CLR FullName used by
    // SchemaMemberComparer at runtime.  UseSpecialTypes must be OFF so that e.g.
    // "float" is emitted as "System.Single" rather than "float"; otherwise the
    // sort order diverges from the runtime and byte-compatibility is broken.
    static readonly SymbolDisplayFormat SortKeyFormat = new SymbolDisplayFormat(
        globalNamespaceStyle:     SymbolDisplayGlobalNamespaceStyle.Omitted,
        typeQualificationStyle:   SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions:          SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions:     SymbolDisplayMiscellaneousOptions.None);

    // -------------------------------------------------------------------------
    // Small helpers / types
    // -------------------------------------------------------------------------

    sealed class SerializedMember
    {
        public string Name    { get; }
        public ITypeSymbol Type { get; }
        public bool IsField   { get; }

        public SerializedMember(string name, ITypeSymbol type, bool isField)
        {
            Name    = name;
            Type    = type;
            IsField = isField;
        }
    }

    /// <summary>Mirrors Ceras's TargetMember enum flags.</summary>
    [Flags]
    enum TargetMemberKind
    {
        None              = 0,
        PublicFields      = 1,
        PrivateFields     = 2,
        PublicProperties  = 4,
        PrivateProperties = 8,
        AllPublic         = PublicFields | PublicProperties,
        AllPrivate        = PrivateFields | PrivateProperties,
        All               = AllPublic | AllPrivate,
    }
}

/// <summary>Diagnostic descriptors produced by the generator.</summary>
static class Diag
{
    public static readonly DiagnosticDescriptor NoSerializableMembers = new(
        id:             "CERAS001",
        title:          "No serializable members found",
        messageFormat:  "Type '{0}' has [GenerateFormatter] but no serializable members were found. Check [Include]/[Exclude] attributes and TargetMembers config.",
        category:       "Ceras.SourceGenerator",
        defaultSeverity: DiagnosticSeverity.Warning,
        isEnabledByDefault: true);
}

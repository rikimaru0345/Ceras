using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Ceras.SourceGenerator
{
    internal static class AccessHelperGenerator
    {
        public static void WritePartialClassHelper(SourceProductionContext context, INamedTypeSymbol type, List<SerializedMember> members)
        {
            var privateMembers = members.Where(m => !m.IsAccessible && SymbolEqualityComparer.Default.Equals(m.DeclaringType, type)).ToList();
            if (privateMembers.Count == 0) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine();

            string ns = type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString();
            if (!string.IsNullOrEmpty(ns))
            {
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
            }

            var typeStack = new Stack<INamedTypeSymbol>();
            var cur = type;
            while (cur != null) { typeStack.Push(cur); cur = cur.ContainingType; }

            int indent = string.IsNullOrEmpty(ns) ? 0 : 4;
            while (typeStack.Count > 0)
            {
                var t = typeStack.Pop();
                string kind = t.TypeKind == TypeKind.Struct ? "struct" : "class";
                sb.AppendLine($"{new string(' ', indent)}partial {kind} {t.Name}");
                sb.AppendLine($"{new string(' ', indent)}{{");
                indent += 4;
            }

            foreach (var m in privateMembers)
            {
                string memberTypeFqn = m.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                if (m.IsField)
                {
                    sb.AppendLine($"{new string(' ', indent)}internal static ref {memberTypeFqn} __ceras_ref_{m.Name}({type.Name} instance) => ref Unsafe.AsRef(in instance.{m.Name});");
                }
                else
                {
                    sb.AppendLine($"{new string(' ', indent)}internal static {memberTypeFqn} __ceras_get_{m.Name}({type.Name} instance) => instance.{m.Name};");
                    if (!m.IsReadOnly)
                        sb.AppendLine($"{new string(' ', indent)}internal static void __ceras_set_{m.Name}({type.Name} instance, {memberTypeFqn} value) => instance.{m.Name} = value;");
                }
            }

            while (indent > (string.IsNullOrEmpty(ns) ? 0 : 4))
            {
                indent -= 4;
                sb.AppendLine($"{new string(' ', indent)}}}");
            }

            if (!string.IsNullOrEmpty(ns))
                sb.AppendLine("}");

            string fileName = $"{type.Name}.Ceras.g.cs";
            context.AddSource(fileName, Microsoft.CodeAnalysis.Text.SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }
}

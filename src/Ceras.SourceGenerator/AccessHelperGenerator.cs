using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Ceras.SourceGenerator
{
    internal static class AccessHelperGenerator
    {
        public static void WritePartialClassHelper(SourceProductionContext context, INamedTypeSymbol type, List<SerializedMember> members)
        {
            var triggeringMembers = members.Where(m => MemberExplorer.NeedsAccessHelper(m) && SymbolEqualityComparer.Default.Equals(m.DeclaringType, type)).ToList();
            if (triggeringMembers.Count == 0) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine();

            string ns = type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString();
            if (!string.IsNullOrEmpty(ns))
            {
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
            }

            var typeStack = new Stack<INamedTypeSymbol>();
            var cur = type;
            while (cur != null) { typeStack.Push(cur); cur = cur.ContainingType; }

            int indent = string.IsNullOrEmpty(ns) ? 0 : 4;
            while (typeStack.Count > 0)
            {
                var t = typeStack.Pop();
                string kind = t.TypeKind == TypeKind.Struct ? "struct" : "class";
                if (t.IsRecord)
                {
                    kind = t.TypeKind == TypeKind.Struct ? "record struct" : "record";
                }
                sb.AppendLine($"{new string(' ', indent)}partial {kind} {t.Name}");
                sb.AppendLine($"{new string(' ', indent)}{{");
                indent += 4;
            }

            foreach (var m in members)
            {
                var req = MemberExplorer.GetAccessHelperRequirement(m);
                if (req == AccessHelperRequirement.None) continue;

                string memberTypeFqn = m.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string instanceModifier = type.IsValueType ? "ref " : "";
                string instanceParam = $"{instanceModifier}{type.Name} instance";
                string safeName = TypeHelpers.SanitizeIdentifier(m.Name);

                if (m.IsField)
                {
                    // Fields use 'ref' which covers both read and write
                    sb.AppendLine($"{new string(' ', indent)}[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, Name = \"{m.Name}\")]");
                    sb.AppendLine($"{new string(' ', indent)}internal static extern ref {memberTypeFqn} __ceras_ref_{safeName}({instanceParam});");
                }
                else
                {
                    if ((req & AccessHelperRequirement.Read) != 0)
                    {
                        sb.AppendLine($"{new string(' ', indent)}[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = \"get_{m.Name}\")]");
                        sb.AppendLine($"{new string(' ', indent)}internal static extern {memberTypeFqn} __ceras_get_{safeName}({instanceParam});");
                    }
                    if ((req & AccessHelperRequirement.Write) != 0)
                    {
                        sb.AppendLine($"{new string(' ', indent)}[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = \"set_{m.Name}\")]");
                        sb.AppendLine($"{new string(' ', indent)}internal static extern void __ceras_set_{safeName}({instanceParam}, {memberTypeFqn} value);");
                    }
                }
            }

            while (indent > (string.IsNullOrEmpty(ns) ? 0 : 4))
            {
                indent -= 4;
                sb.AppendLine($"{new string(' ', indent)}}}");
            }

            if (!string.IsNullOrEmpty(ns))
                sb.AppendLine("}");

            string typeName = TypeHelpers.SanitizeIdentifier(type.ToDisplayString(TypeHelpers.FullyQualifiedNoGlobal));
            string fileName = $"{typeName}.Access.Ceras.g.cs";
            context.AddSource(fileName, Microsoft.CodeAnalysis.Text.SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }
}

using System;
using System.Linq;
using Ceras;
using Ceras.Resolvers;
using Ceras.Generated;
using Ceras.Test;

namespace Ceras.TestDebugger
{
    public class RobustRepro
    {
        public static void Run()
        {
            var generatedCeras = new CerasSerializer(GeneratedConfig());
            var dynamicCeras   = new CerasSerializer(new SerializerConfig());

            var obj = new Item { Name = "Mithril Helm", Quantity = 123456, Rarity = ItemRarity.Epic, Weight = 3.7f };
            Console.WriteLine($"Serializing: Name='{obj.Name}', Quantity={obj.Quantity}, Rarity={obj.Rarity}, Weight={obj.Weight}");

            var meta = dynamicCeras.Advanced.GetFormatterResolver<ReflectionFormatterResolver>().GetFormatter(typeof(Item));
            // Actually, let's just look at the PrimarySchema
            var primarySchema = ((ICerasAdvanced)dynamicCeras).GetFormatterResolver<ReflectionFormatterResolver>().GetFormatter(typeof(Item));
            // I can't easily get the schema from here.
            
            Console.WriteLine("Field order according to SchemaMemberComparer:");
            var members = typeof(Item).GetFields(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance).ToList();
            members.Sort((a, b) => {
                var ka = a.FieldType.FullName + a.Name + a.DeclaringType.FullName + "f";
                var kb = b.FieldType.FullName + b.Name + b.DeclaringType.FullName + "f";
                return string.Compare(ka, kb, StringComparison.Ordinal);
            });
            foreach(var m in members) Console.WriteLine($" - {m.FieldType.Name} {m.Name}");

            var dynamicBytes = dynamicCeras.Serialize(obj);
            var generatedBytes = generatedCeras.Serialize(obj);

            Console.WriteLine("Dynamic bytes:   " + string.Join("-", dynamicBytes.Select(b => b.ToString("X2"))));
            Console.WriteLine("Generated bytes: " + string.Join("-", generatedBytes.Select(b => b.ToString("X2"))));

            if (dynamicBytes.Length != generatedBytes.Length)
                Console.WriteLine($"Length mismatch: Dynamic={dynamicBytes.Length}, Generated={generatedBytes.Length}");
        }

        static SerializerConfig GeneratedConfig()
        {
            var c = new SerializerConfig();
            RobustFormatters.UseRobustFormatters(c);
            return c;
        }
    }
}
